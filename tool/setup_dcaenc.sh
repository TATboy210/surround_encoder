# Builds dcaenc — the independent LGPL DTS Coherent Acoustics (DCA) encoder
# based on the public ETSI TS 102 366 standard — as a shared library, and
# installs a dev layout (include/ + lib/ [+ bin/]) into
# native/dcaenc/<triplet>/.
#
# Usage: ./tool/setup_dcaenc.sh [triplet]   (auto-detected if omitted)
set -euo pipefail

DCAENC_TAG="${DCAENC_TAG:-master}"
TRIPLET="${1:-}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT_ROOT="$REPO_ROOT/native/dcaenc"
SRC_DIR="$OUTPUT_ROOT/dcaenc-src"

if [ -z "$TRIPLET" ]; then
  case "$(uname -s)-$(uname -m)" in
    Darwin-arm64)  TRIPLET="arm64-osx" ;;
    Darwin-*)      TRIPLET="x64-darwin" ;;
    Linux-aarch64) TRIPLET="linux-arm64" ;;
    Linux-*)       TRIPLET="linux-x64" ;;
    *) echo "Unsupported host: $(uname -s) $(uname -m)"; exit 1 ;;
  esac
fi

mkdir -p "$OUTPUT_ROOT" "$SRC_DIR"

if [ ! -f "$SRC_DIR/dcaenc.c" ]; then
  echo "Cloning dcaenc..."
  git clone --depth 1 https://gitlab.com/patrakov/dcaenc.git "$SRC_DIR"
fi

PREFIX="$OUTPUT_ROOT/$TRIPLET"
mkdir -p "$PREFIX/include" "$PREFIX/lib"
cp "$SRC_DIR/dcaenc.h" "$PREFIX/include/dcaenc.h"

# dcaenc.c includes "config.h" (autotools-generated upstream) but references
# no feature macros; an empty one is sufficient.
if [ ! -f "$SRC_DIR/config.h" ]; then
  printf '/* generated by setup_dcaenc.sh */\n' > "$SRC_DIR/config.h"
fi

BUILD_DIR="$OUTPUT_ROOT/build-$TRIPLET"
mkdir -p "$BUILD_DIR"

echo "Building the math table generator..."
cc -O2 "$SRC_DIR/gentables.c" -o "$BUILD_DIR/gentables" -lm
"$BUILD_DIR/gentables" > "$BUILD_DIR/math_tables.c"

case "$(uname -s)" in
  Darwin)
    echo "Building libdcaenc.dylib for $TRIPLET..."
    cc -O2 -fPIC -shared "$SRC_DIR/dcaenc.c" "$BUILD_DIR/math_tables.c" \
       -o "$PREFIX/lib/libdcaenc.dylib" -I"$SRC_DIR"
    ;;
  *)
    echo "Building libdcaenc.so for $TRIPLET..."
    gcc -O2 -fPIC -shared "$SRC_DIR/dcaenc.c" "$BUILD_DIR/math_tables.c" \
       -o "$PREFIX/lib/libdcaenc.so" -I"$SRC_DIR"
    ;;
esac

echo "dcaenc installed to $PREFIX"
