# Builds dcaenc — the independent LGPL DTS Coherent Acoustics (DCA) encoder
# based on the public ETSI TS 102 366 standard — into a Windows DLL using
# MSYS2 MinGW gcc, then generates MSVC-importable .lib files from a fixed
# .def export list.
#
# Usage: .\tool\setup_dcaenc.ps1 [-Triplet x64-windows] [-Msys2Root D:\tools\msys64]
param(
  [string]$Triplet = 'x64-windows',
  [string]$Msys2Root = 'C:\msys64',
  [string]$DcaencTag = 'master'
)

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
$OutputRoot = Join-Path $RepoRoot 'native\dcaenc'
# The plugin's CMake discovers native/dcaenc/windows-<arch>.
$LayoutName = if ($Triplet -match '^arm64') { 'windows-arm64' } else { 'windows-x64' }
$Prefix = Join-Path $OutputRoot $LayoutName
$SrcDir = Join-Path $OutputRoot 'dcaenc-src'

# Convert a Windows path to its MSYS2 form (C:\foo\bar -> /c/foo/bar).
function ConvertTo-MsysPath([string]$path) {
  $p = $path -replace '\\', '/'
  if ($p -match '^([A-Za-z]):/(.*)$') {
    return '/' + $Matches[1].ToLower() + '/' + $Matches[2]
  }
  return $p
}

if (-not (Test-Path (Join-Path $Msys2Root 'usr\bin\bash.exe'))) {
  throw "MSYS2 not found at $Msys2Root. Install it from https://msys2.org `
    and pass -Msys2Root."
}

# --- locate lib.exe -------------------------------------------------------
$VsWhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
if (-not (Test-Path $VsWhere)) { throw 'vswhere.exe not found - install Visual Studio Build Tools' }
$VsPath = & $VsWhere -latest -property installationPath
$LibExe = Get-ChildItem -Path (Join-Path $VsPath 'VC\Tools\MSVC') -Recurse `
  -Filter lib.exe | Select-Object -First 1 -ExpandProperty FullName
if (-not $LibExe) { throw 'lib.exe not found under the VS installation' }

# --- source ---------------------------------------------------------------
if (-not (Test-Path (Join-Path $SrcDir 'dcaenc.c'))) {
  Write-Host 'Cloning dcaenc...'
  & git clone --depth 1 https://gitlab.com/patrakov/dcaenc.git $SrcDir
  if ($LASTEXITCODE -ne 0) { throw 'git clone failed' }
}

# --- build via MSYS2 (MinGW gcc exports all public symbols by default) ----
New-Item -ItemType Directory -Force -Path "$Prefix\include", "$Prefix\lib", "$Prefix\bin" | Out-Null
Copy-Item -Force (Join-Path $SrcDir 'dcaenc.h') "$Prefix\include\dcaenc.h"
# dcaenc.c includes "config.h" (autotools-generated upstream) but the library
# core references no feature macros; an empty one is sufficient.
if (-not (Test-Path (Join-Path $SrcDir 'config.h'))) {
  Set-Content -Path (Join-Path $SrcDir 'config.h') -Value '/* generated by setup_dcaenc.ps1 */' -Encoding ASCII
}

$BashScript = @"
set -e
export PATH=/ucrt64/bin:`$PATH
mkdir -p '$(ConvertTo-MsysPath "$OutputRoot\build-$Triplet")'
gcc -O2 '$(ConvertTo-MsysPath $SrcDir)/gentables.c' -o '$(ConvertTo-MsysPath "$OutputRoot\build-$Triplet\gentables.exe")' -lm
'$(ConvertTo-MsysPath "$OutputRoot\build-$Triplet\gentables.exe")' > '$(ConvertTo-MsysPath "$OutputRoot\build-$Triplet\math_tables.c")'
gcc -O2 -shared '$(ConvertTo-MsysPath $SrcDir)/dcaenc.c' '$(ConvertTo-MsysPath "$OutputRoot\build-$Triplet\math_tables.c")' -o '$(ConvertTo-MsysPath "$Prefix\bin\dcaenc.dll")' -I'$(ConvertTo-MsysPath $SrcDir)'
"@
$TmpScript = Join-Path $env:TEMP 'surround-dcaenc-build.sh'
Set-Content -Path $TmpScript -Value $BashScript -Encoding ASCII

Write-Host 'Building dcaenc.dll...'
& (Join-Path $Msys2Root 'usr\bin\bash.exe') -lc "bash '$(ConvertTo-MsysPath $TmpScript)'"
if ($LASTEXITCODE -ne 0 -or -not (Test-Path "$Prefix\bin\dcaenc.dll")) {
  throw 'dcaenc.dll build failed'
}
Write-Host 'dcaenc.dll built.'

# --- exports --------------------------------------------------------------
# The stable public API of dcaenc (dcaenc.h) lives in tool/dcaenc.def;
# MinGW would also export private symbols, so the .def list keeps the import
# library minimal and stable.
$DefPath = Join-Path $RepoRoot 'tool\dcaenc.def'
if (-not (Test-Path $DefPath)) { throw "dcaenc.def not found at $DefPath" }
Copy-Item -Force $DefPath (Join-Path $Prefix 'lib\dcaenc.def')

& $LibExe "/def:$DefPath" "/machine:X64" "/out:$(Join-Path $Prefix 'lib\dcaenc.lib')"
if ($LASTEXITCODE -ne 0) { throw 'lib.exe failed for dcaenc' }

Write-Host ''
Write-Host "dcaenc installed to $Prefix"
Get-ChildItem "$Prefix\bin", "$Prefix\lib" -File | ForEach-Object {
  Write-Host ("  {0}  {1:N0} KB" -f $_.Name, ($_.Length / 1KB))
}
